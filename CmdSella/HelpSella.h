#ifndef HELPSELLA_H
#define HELPSELLA_H

// HelpSella.h (2026-11-10) -- the text printed by the HELP (or ?) control.
// Lists only the controls a normal user needs; the development and
// diagnostic controls are named at the end and documented in
// CmdSellaControls.h.

#include <iostream>

inline void ShowSellaHelp() {
   static const char* const lines[] = {
      "; CmdSella -- SELLA lattice symmetry search",
      ";",
      "; For an input cell, finds the Bravais lattice types it is close to,",
      "; how close (a distance in A^2), and the conventional cell of each.",
      ";",
      "; HOW IT WORKS",
      ";   The cell is Selling-reduced and written as an S6 vector: the six",
      ";   scalars b.c, a.c, a.b, a.d, b.d, c.d, with d = -(a+b+c).",
      ";   Each of the 24 Delone types is a set of linear subspaces of S6, one",
      ";   for each arrangement of its reduced form. The fit for a type is the",
      ";   distance from the input to the nearest reduced cell of that type",
      ";   (a projection, kept inside the region of reduced cells).",
      ";   Close to a boundary of that region, the nearest cell of a type can",
      ";   belong to a different reduced form of the same lattice; those forms",
      ";   are searched too, so the fit does not depend on which reduced cell",
      ";   the reduction happened to give.",
      ";   A type is reported as a match when its fit is small compared with",
      ";   the size of the S6 vector (MAXDELTA). Triclinic (A1) always fits",
      ";   with 0.",
      ";",
      "; INPUT FORMAT",
      ";   One cell per line:  <lattice> a b c alpha beta gamma",
      ";   Lattice letters: P I A B C F R H",
      ";   Example:  I 10 10.01 10.02 90.1 90.2 90.3",
      ";   An S6 vector may be given instead:  S s1 s2 s3 s4 s5 s6",
      ";   Finish input with:  end",
      ";",
      ";   R or H: read as rhombohedral centering on hexagonal axes (obverse)",
      ";   when the cell is closer to a = b, 90, 90, 120 than to a = b = c with",
      ";   equal angles; otherwise as rhombohedral axes (a primitive cell).",
      ";   The reading is printed after the input line.",
      ";",
      "; CONTROL KEYWORDS (enter before 'end')",
      ";",
      ";   HELP  or  ?",
      ";      Show this message.",
      ";",
      ";   DOGRAPHICS <0 | 1>",
      ";      Write three SVG plots for each cell (default 1).",
      ";",
      ";   TYPES <list>",
      ";      Show only these Delone types in 'Fits for Types' and in COMPARE,",
      ";      e.g.  TYPES O1B O2 O3   (all 24 are still computed).",
      ";",
      ";   MAXDELTA <value>",
      ";      Match threshold: a type matches when its fit is below",
      ";      MAXDELTA times the length of the reduced S6 vector (default 0.02).",
      ";",
      ";   PRECISION <n>",
      ";      Print the fits with n decimals, and for each type its winning",
      ";      candidate and projected S6 vectors.",
      ";",
      ";   COMPARE",
      ";      Instead of the output for each cell, print one table for all",
      ";      input cells: fit, type, cell, grouped by type.",
      ";",
      ";   BLOCKSTART <n>   BLOCKSIZE <n>",
      ";      Process only BLOCKSIZE cells, starting at cell BLOCKSTART",
      ";      (for long runs; runs from the web page are limited by the number",
      ";      of files written).",
      ";",
      ";   TEST [n] [n2] ...",
      ";      Run the built-in tests: all of them, or only those numbered.",
      ";",
      "; OUTPUT",
      ";   Fits for Types",
      ";      Bravais type, Delone type, fit (A^2), for all 24 Delone types.",
      ";   Projected best fits",
      ";      For each matching type, the nearest cell of that type (primitive).",
      ";   Conventional cells, for each matching type:",
      ";      idealized -- the nearest lattice of the type, with exact symmetry",
      ";      input     -- the input lattice in the same setting",
      ";      basis     -- comment line: rows A B C of that conventional cell",
      ";                   in terms of the typed a b c (fractions for centered",
      ";                   input)",
      ";   Settings: mC is C-centered with b unique, and the I2/m cell is also",
      ";   given when the C2/m beta exceeds 120 degrees; mP has b unique; hR is",
      ";   given on rhombohedral axes and printed with the letter P.",
      ";   The cell lines have the same layout as the input, so they can be",
      ";   passed on to the other LRL programs.",
      ";",
      "; DEVELOPMENT AND DIAGNOSTIC CONTROLS",
      ";   FACECROSSED, REMEDIATION, CONEFIT, CHECKNESTING, CHECKREMEDIATION,",
      ";   NESTINGDELTA, SEED, DETAILS, SIGMAS -- see CmdSellaControls.h.",
      ";",
      "; EXAMPLE SESSION",
      ";   DOGRAPHICS 0",
      ";   I 10 10.01 10.02 90.1 90.2 90.3",
      ";   end",
      ";"
   };
   for (const char* const line : lines) {
      std::cout << line << std::endl;
   }
}

#endif // HELPSELLA_H
